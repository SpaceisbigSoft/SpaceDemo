#!/bin/sh
# Builds engine/src/voice/speex-wasm.ts: the official Xiph Speex decoder (narrowband, fixed point, decoder only)
# compiled to WebAssembly with clang + wasm-ld, embedded as base64 so the app and the command-line tools need no
# extra file. Speex: BSD licence (Xiph.org), https://github.com/xiph/speex — the source is fetched, not committed.
#   sh helpers/speex/build.sh [path to a speex checkout]   (default: clones it into out/speex-src)
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
SRC=${1:-$ROOT/out/speex-src}
[ -d "$SRC/libspeex" ] || git clone --depth 1 https://github.com/xiph/speex "$SRC"
OUT=$ROOT/out/speex-build; rm -rf "$OUT"; mkdir -p "$OUT/inc"
cp "$HERE"/inc/* "$OUT/inc/"
for h in math.h stdlib.h string.h stdio.h; do echo '#include "shim.h"' > "$OUT/inc/$h"; done
FILES="bits.c cb_search.c exc_10_16_table.c exc_10_32_table.c exc_20_32_table.c exc_5_256_table.c exc_5_64_table.c exc_8_128_table.c filters.c gain_table.c gain_table_lbr.c lpc.c lsp.c lsp_tables_nb.c ltp.c modes.c nb_celp.c quant_lsp.c speex.c speex_callbacks.c vq.c window.c"
CF="--target=wasm32 -O2 -ffreestanding -nostdlib -fno-builtin -DHAVE_CONFIG_H -I $OUT/inc -I $SRC/libspeex -I $SRC/include"
for f in $FILES; do clang $CF -c "$SRC/libspeex/$f" -o "$OUT/${f%.c}.o"; done
for f in shim.c glue.c; do clang $CF -c "$HERE/$f" -o "$OUT/${f%.c}.o"; done
wasm-ld --no-entry --gc-sections --export=dec_new --export=dec_free --export=dec_frame --export=dec_lost --export=buf --export=unbuf -o "$OUT/speexdec.wasm" "$OUT"/*.o
COMMIT=$(git -C "$SRC" rev-parse --short HEAD 2>/dev/null || echo unknown)
{
  echo "// Generated by helpers/speex/build.sh from Xiph Speex @ $COMMIT (BSD licence, see helpers/speex/COPYING). Do not edit."
  printf "export const SPEEX_WASM_BASE64 = '"; base64 -w0 "$OUT/speexdec.wasm"; echo "';"
} > "$ROOT/engine/src/voice/speex-wasm.ts"
echo "engine/src/voice/speex-wasm.ts written ($(wc -c < "$OUT/speexdec.wasm") bytes of WebAssembly)"
