import { readDemo } from '../../engine/src/container/read.js';
import { extractMatch } from '../../engine/src/match/extract.js';
import { readZipEntry } from '../../engine/src/zip.js';
import { findCandidates } from '../../app/main/library.js';
import { demoPlayers, playerTotals } from '../../app/main/players.js';
const seen = new Set<string>();
const cands = findCandidates([process.argv[2]]).candidates.filter((c) => !seen.has(c.name) && seen.add(c.name));
const t0 = Date.now();
const demos = cands.map((c) => demoPlayers(extractMatch(readDemo(readZipEntry(c.file, c.zipEntry!))), { key: c.key, name: c.name, date: c.mtime, map: '' }));
console.log('demos', demos.length, 'ms', Date.now() - t0);
const v = playerTotals(demos, {}, []);
console.log('counted once:', v.demos.filter(d => d.countedAs).map(d => d.name + '→' + v.demos.find(x => x.key === d.countedAs)!.name).join(', '));
console.log('players', v.players.length); console.log(v.players.slice(0, 12).map(p => `${p.name} ${p.demos}d ${p.kills}/${p.deaths} [${p.tags}]`).join('\n'));
console.log('suggestions', v.suggestions.length); for (const s of v.suggestions.slice(0, 25)) console.log(s.score, s.a, '=', s.b, '|', s.reasons.join('; '));
